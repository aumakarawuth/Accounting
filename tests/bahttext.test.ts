import { describe, it, expect } from 'vitest';
import { bahtText } from '../apps/web/lib/bahttext';

// จำนวนเงินตัวอักษรบนเอกสาร (เทียบกับ BAHTTEXT ที่ใช้ในโปรแกรมบัญชีไทยทั่วไป)
describe('bahtText', () => {
  it.each([
    ['0.00', 'ศูนย์บาทถ้วน'],
    ['1', 'หนึ่งบาทถ้วน'],
    ['11', 'สิบเอ็ดบาทถ้วน'],
    ['21', 'ยี่สิบเอ็ดบาทถ้วน'],
    ['101', 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    ['220', 'สองร้อยยี่สิบบาทถ้วน'],
    ['13375.00', 'หนึ่งหมื่นสามพันสามร้อยเจ็ดสิบห้าบาทถ้วน'],
    ['1000000', 'หนึ่งล้านบาทถ้วน'],
    ['1000001', 'หนึ่งล้านเอ็ดบาทถ้วน'],
    ['21000000', 'ยี่สิบเอ็ดล้านบาทถ้วน'],
    ['1234567.89', 'หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทแปดสิบเก้าสตางค์'],
    ['0.50', 'ห้าสิบสตางค์'],
    ['1.01', 'หนึ่งบาทหนึ่งสตางค์'],
    ['100.21', 'หนึ่งร้อยบาทยี่สิบเอ็ดสตางค์'],
    ['10700.5', 'หนึ่งหมื่นเจ็ดร้อยบาทห้าสิบสตางค์'],
  ])('%s → %s', (n, w) => expect(bahtText(n)).toBe(w));
});
